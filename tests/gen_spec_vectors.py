"""Generate tests/native/spec_vectors.hpp from ARIB STD-T99 Annex 2 7.7.2 (test signals).

Input is the text of the English edition made by `pdftotext -layout 5-STD-T99v4_1-E1.pdf`.
Each frame lists the whitened symbols in hexadecimal (di-bit notation, MSB first).
Usage: python tests/gen_spec_vectors.py t99.txt tests/native/spec_vectors.hpp
"""
import re
import sys


def frames(text):
    start = text.rindex('7.7.2.1 Voice Communication Test Signal')   # body, not the table of contents
    end = text.index('7.8 Receiving Connection Test', start)
    test, current, out = None, None, []
    field = re.compile(r'^(P|SW|RICH|SACCH|PICH1|PICH2|TCH|FACCH)\s*(\((?:1st|2nd) half\)|\(\d/4\))?\s*:\s*([0-9A-F ]+)$')
    for line in text[start:end].splitlines():
        line = line.strip()
        m = re.search(r'Test signal (\d-\d)', line)
        if m:
            test = m.group(1)
            continue
        m = re.match(r'^Frame (\d+|n)\b', line)
        if m:
            current = {'test': test, 'frame': m.group(1), 'fields': {}}
            out.append(current)
            line = line[m.end():].strip()
            if line.startswith(':'):          # "Frame 1  : CDF5 9" (SW printed on the frame line)
                line = 'SW ' + line
        if line == 'SW' or not current:
            continue
        m = field.match(line)
        if m:
            half = m.group(2) or ''
            key = m.group(1) + ('1' if '1st' in half else '2' if '2nd' in half else '')
            current['fields'][key] = m.group(3).replace(' ', '')
    return out


def bits(hexdigits, n):
    return bin(int(hexdigits, 16))[2:].zfill(len(hexdigits) * 4)[:n]


def main():
    text = open(sys.argv[1], encoding='utf-8', errors='ignore').read()
    rows = []
    for f in frames(text):
        d = f['fields']
        first = d.get('PICH1') or d.get('TCH1') or d.get('FACCH1')
        second = d.get('PICH2') or d.get('TCH2') or d.get('FACCH2')
        b = bits(d['SW'], 20) + bits(d['RICH'], 16) + bits(d['SACCH'], 60) + bits(first, 144) + bits(second, 144)
        assert len(b) == 384, f
        symbols = [{'00': 1, '01': 3, '10': -1, '11': -3}[b[i:i + 2]] for i in range(0, 384, 2)]
        number = -1 if f['frame'] == 'n' else int(f['frame'])
        rows.append(f'  {{"{f["test"]}", {number}, {{{",".join(map(str, symbols))}}}}},')
    with open(sys.argv[2], 'w', encoding='utf-8', newline='\n') as out:
        out.write('// Generated by tests/gen_spec_vectors.py from ARIB STD-T99 Annex 2 7.7.2 (test signals). Do not edit.\n')
        out.write('// Whitened transmitted symbols of every listed frame; frame -1 = "Frame n" (end of call).\n')
        out.write('#pragma once\n#include <array>\n#include <cstdint>\n#include <vector>\n')
        out.write('namespace t99::spec {\nstruct Vector { const char* test; int frame; std::array<int8_t, 192> symbols; };\n')
        out.write('inline const std::vector<Vector>& vectors() { static const std::vector<Vector> v = {\n')
        out.write('\n'.join(rows))
        out.write('\n}; return v; }\n}\n')
    print(f'{len(rows)} frames')


if __name__ == '__main__':
    main()
